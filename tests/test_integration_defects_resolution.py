# DEF-INT-013: SLA breach acknowledgment is idempotent
# ==============================================================================
def test_def_int_013_sla_breach_acknowledgment_is_idempotent(test_setup):
    org = test_setup["org"]
    site = test_setup["site"]
    owner_u = test_setup["owner_user"]

    wo = wo_services.create_work_order(
        org,
        site=site,
        asset=test_setup["asset"],
        title="SLA Breach WO",
        actor=owner_u,
    )

    profile = SLAProfile.objects.create(
        organization=org,
        name="Standard WO SLA",
        applies_to=SLAProfile.AppliesTo.WORK_ORDER,
    )

    tracking = SLATracking.objects.create(
        organization=org,
        work_order=wo,
        site=site,
        profile=profile,
        started_at=timezone.now(),
        response_minutes=60,
        resolution_minutes=240,
        warning_percent=80,
        priority="P1",
        response_due_at=timezone.now(),
        resolution_due_at=timezone.now(),
    )
    breach = SLABreach.objects.create(
        organization=org,
        tracking=tracking,
        profile=profile,
        site=site,
        target_kind="RESPONSE",
        priority="P1",
        breached_at=timezone.now(),
        detected_at=timezone.now(),
        status=SLABreach.Status.OPEN,
    )

    # First acknowledgment
    res1 = sla_services.acknowledge_breach(breach, actor=owner_u)
    assert res1.status == SLABreach.Status.ACKNOWLEDGED
    assert res1.acknowledged_by == owner_u

    # Second acknowledgment is idempotent (no Conflict 409)
    res2 = sla_services.acknowledge_breach(breach, actor=owner_u)
    assert res2.status == SLABreach.Status.ACKNOWLEDGED
