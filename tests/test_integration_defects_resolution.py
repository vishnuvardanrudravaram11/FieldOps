# DEF-INT-002: Outbox retry limit (max_retries) honoured
# ==============================================================================
def test_def_int_002_outbox_retry_limit_honoured(test_setup):
    org = test_setup["org"]
    WebhookEndpoint.objects.create(
        organization=org,
        target_url="http://localhost:9999/webhook/failing/",
        event_pattern="*",
        is_active=True,
    )
    event = publish_integration_event(
        organization=org,
        event_type="test.retry.limit",
        aggregate_type="test",
        aggregate_id="456",
        payload={"message": "fail"},
    )
    event.max_retries = 2
    event.save(update_fields=["max_retries"])

    with patch("urllib.request.urlopen", side_effect=RuntimeError("500 Internal Server Error")):
        # Run poller multiple times (e.g. 6 times)
        for _ in range(6):
            process_pending_events(batch_size=10)

    event.refresh_from_db()
    assert event.status == IntegrationEvent.Status.FAILED
    assert event.retry_count == 2
    # Ensure further process_pending_events does not re-process FAILED event
    with patch("urllib.request.urlopen") as mock_call:
        count = process_pending_events(batch_size=10)
        assert count == 0
        assert mock_call.call_count == 0


