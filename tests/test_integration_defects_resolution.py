# DEF-INT-007: Swagger marks required query parameters
# ==============================================================================
def test_def_int_007_swagger_query_parameters_marked_required():
    from drf_spectacular.generators import SchemaGenerator

    generator = SchemaGenerator()
    schema = generator.get_schema(request=None, public=True)
    paths = schema.get("paths", {})

    # 1. resolve endpoint requires 'token'
    resolve_path = paths.get("/api/v1/asset-identifiers/resolve/")
    assert resolve_path is not None
    resolve_params = resolve_path.get("get", {}).get("parameters", [])
    token_param = next((p for p in resolve_params if p.get("name") == "token"), None)
    assert token_param is not None
    assert token_param.get("required") is True

    # 2. coverage endpoint requires 'asset'
    coverage_path = paths.get("/api/v1/coverage/")
    assert coverage_path is not None
    coverage_params = coverage_path.get("get", {}).get("parameters", [])
    asset_param = next((p for p in coverage_params if p.get("name") == "asset"), None)
    assert asset_param is not None
    assert asset_param.get("required") is True

    # 3. requirements endpoint requires 'work_order'
    req_path = paths.get("/api/v1/inspections/requirements/")
    assert req_path is not None
    req_params = req_path.get("get", {}).get("parameters", [])
    wo_param = next((p for p in req_params if p.get("name") == "work_order"), None)
    assert wo_param is not None
    assert wo_param.get("required") is True


