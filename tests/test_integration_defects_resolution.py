# DEF-INT-003: Portal account auto_grant_assets default False
# ==============================================================================
def test_def_int_003_portal_account_auto_grant_assets_defaults_false(test_setup):
    org = test_setup["org"]
    client_u = User.objects.create_user(email="client_grant_test@external.com")
    client_m = Membership.objects.create(user=client_u, organization=org, status=Membership.Status.ACTIVE)
    role_client = system_role_by_key(org, "client_requester")
    set_membership_roles(client_m, [role_client], actor=test_setup["owner_user"], system=True)

    account = portal_services.create_portal_account(
        organization=org,
        membership=client_m,
        company_name="Acme Clients",
    )
    assert account.auto_grant_assets is False

    # Client sees 0 assets since no explicit grant exists
    client = APIClient()
    client.force_authenticate(user=client_u)
    resp = client.get("/api/v1/portal/assets/", HTTP_X_ORGANIZATION=org.slug)
    assert resp.status_code == 200
    assert resp.json()["count"] == 0

    # Client cannot create a request for an ungranted asset
    req_resp = client.post(
        "/api/v1/portal/requests/",
        data={
            "title": "Broken equipment",
            "description": "Please check this unit immediately.",
            "asset": str(test_setup["asset"].pk),
            "kind": "INCIDENT",
            "urgency": "HIGH",
        },
        format="json",
        HTTP_X_ORGANIZATION=org.slug,
    )
    assert req_resp.status_code in (400, 403, 404)


