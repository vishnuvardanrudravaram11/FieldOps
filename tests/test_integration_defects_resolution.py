# DEF-INT-001: Webhook single delivery (no duplicate delivery)
# ==============================================================================
def test_def_int_001_webhook_delivered_exactly_once(test_setup):
    org = test_setup["org"]
    ep = WebhookEndpoint.objects.create(
        organization=org,
        target_url="http://localhost:9999/webhook/",
        event_pattern="*",
        is_active=True,
    )
    assert ep.is_active
    event = publish_integration_event(
        organization=org,
        event_type="test.event.published",
        aggregate_type="test",
        aggregate_id="123",
        payload={"message": "hello"},
    )

    with patch("urllib.request.urlopen") as mock_urlopen:
        mock_urlopen.return_value.__enter__.return_value.status = 200
        deliver_event(event)

        # Must be called exactly once for this endpoint, not twice
        assert mock_urlopen.call_count == 1


